#!/usr/bin/env python3
"""Generate the native project and localization from tracked, canonical inputs (stdlib only)."""

import hashlib
import json
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[2]
IOS = ROOT / "ios"


def identifier(name):
    return hashlib.sha256(name.encode()).hexdigest()[:24].upper()


def write_if_changed(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    data = value.encode() if isinstance(value, str) else value
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def quote(value):
    return json.dumps(str(value), ensure_ascii=False)


def plist(value, level=0):
    """Serialize the OpenStep property-list subset used by Xcode projects."""
    indent = "\t" * level
    if isinstance(value, dict):
        lines = ["{"]
        for key, item in value.items():
            lines.append(f"{indent}\t{quote(key)} = {plist(item, level + 1)};")
        return "\n".join(lines) + "\n" + indent + "}"
    if isinstance(value, list):
        return "(" + ", ".join(plist(item, level) for item in value) + ")"
    return quote(value)


def localization():
    source = (ROOT / "assets/i18n/en-US/main.ftl").read_text()
    strings = dict(re.findall(r"^(ios-[a-z0-9-]+) = (.*)$", source, re.MULTILINE))
    used = set()
    for path in (IOS / "Sonora").glob("*.swift"):
        used.update(re.findall(r'"(ios-[a-z0-9-]+)"', path.read_text()))
    missing = used - strings.keys()
    if missing:
        raise ValueError(f"Missing canonical Fluent strings: {sorted(missing)}")
    body = "// Generated by ios/scripts/prepare.py. Do not edit.\n"
    body += "\n".join(f"{quote(k)} = {quote(v)};" for k, v in sorted(strings.items())) + "\n"
    write_if_changed(IOS / "Sonora/Resources/en.lproj/Localizable.strings", body)


def icon():
    # Extract the existing 1024px master render, without inventing or resizing brand artwork.
    data = (ROOT / "assets/macos/sonora.icns").read_bytes()
    if data[:4] != b"icns":
        raise ValueError("Invalid upstream icon container")
    offset = 8
    while offset + 8 <= len(data):
        kind = data[offset:offset + 4]
        size = struct.unpack(">I", data[offset + 4:offset + 8])[0]
        if size < 8 or offset + size > len(data):
            raise ValueError("Invalid upstream icon chunk")
        if kind == b"ic10":
            image = data[offset + 8:offset + size]
            if not image.startswith(b"\x89PNG"):
                raise ValueError("The upstream master render is not PNG")
            base = IOS / "Sonora/Assets.xcassets/AppIcon.appiconset"
            write_if_changed(base / "AppIcon.png", image)
            write_if_changed(base / "Contents.json", json.dumps({
                "images": [{"filename": "AppIcon.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"}],
                "info": {"author": "xcode", "version": 1}
            }, indent=2) + "\n")
            return
        offset += size
    raise ValueError("No 1024px upstream icon found")


def project():
    objects = {}

    def add(identity, isa, **fields):
        key = identifier(identity)
        objects[key] = {"isa": isa, **fields}
        return key

    source_refs, source_builds = [], []
    for path in sorted((IOS / "Sonora").glob("*.swift")):
        relative = str(path.relative_to(IOS))
        ref = add(relative, "PBXFileReference", lastKnownFileType="sourcecode.swift", path=relative, sourceTree="SOURCE_ROOT")
        source_refs.append(ref)
        source_builds.append(add(relative + ".build", "PBXBuildFile", fileRef=ref))

    strings = add("strings.en", "PBXFileReference", lastKnownFileType="text.plist.strings", name="en", path="Sonora/Resources/en.lproj/Localizable.strings", sourceTree="SOURCE_ROOT")
    variant = add("strings", "PBXVariantGroup", children=[strings], name="Localizable.strings", sourceTree="<group>")
    assets = add("assets", "PBXFileReference", lastKnownFileType="folder.assetcatalog", path="Sonora/Assets.xcassets", sourceTree="SOURCE_ROOT")
    resources = [add("strings.build", "PBXBuildFile", fileRef=variant), add("assets.build", "PBXBuildFile", fileRef=assets)]
    info = add("info", "PBXFileReference", lastKnownFileType="text.plist.xml", path="Sonora/Info.plist", sourceTree="SOURCE_ROOT")
    app = add("app", "PBXFileReference", explicitFileType="wrapper.application", path="Sonora.app", sourceTree="BUILT_PRODUCTS_DIR", includeInIndex="0")
    source_group = add("source.group", "PBXGroup", children=source_refs + [variant, assets, info], name="Sonora", sourceTree="<group>")
    products = add("products", "PBXGroup", children=[app], name="Products", sourceTree="<group>")
    main_group = add("main.group", "PBXGroup", children=[source_group, products], sourceTree="<group>")
    sources = add("sources", "PBXSourcesBuildPhase", buildActionMask="2147483647", files=source_builds, runOnlyForDeploymentPostprocessing="0")
    resource_phase = add("resources", "PBXResourcesBuildPhase", buildActionMask="2147483647", files=resources, runOnlyForDeploymentPostprocessing="0")
    frameworks = add("frameworks", "PBXFrameworksBuildPhase", buildActionMask="2147483647", files=[], runOnlyForDeploymentPostprocessing="0")
    project_configs, target_configs = [], []
    for name in ["Debug", "Release"]:
        project_configs.append(add("project." + name, "XCBuildConfiguration", name=name, buildSettings={
            "SDKROOT": "iphoneos", "IPHONEOS_DEPLOYMENT_TARGET": "26.0",
            "CLANG_ENABLE_MODULES": "YES", "SWIFT_VERSION": "5.0",
            "SWIFT_OPTIMIZATION_LEVEL": "-Onone" if name == "Debug" else "-O",
            "SWIFT_COMPILATION_MODE": "singlefile" if name == "Debug" else "wholemodule",
            "DEBUG_INFORMATION_FORMAT": "dwarf" if name == "Debug" else "dwarf-with-dsym",
            "SWIFT_ACTIVE_COMPILATION_CONDITIONS": "DEBUG" if name == "Debug" else "",
        }))
        target_configs.append(add("target." + name, "XCBuildConfiguration", name=name, buildSettings={
            "PRODUCT_NAME": "Sonora", "PRODUCT_BUNDLE_IDENTIFIER": "org.sonorahq.iphone.development",
            "INFOPLIST_FILE": "Sonora/Info.plist", "GENERATE_INFOPLIST_FILE": "NO",
            "TARGETED_DEVICE_FAMILY": "1", "SUPPORTED_PLATFORMS": "iphoneos iphonesimulator",
            "SUPPORTS_MACCATALYST": "NO", "SUPPORTS_MAC_DESIGNED_FOR_IPHONE_IPAD": "NO",
            "ASSETCATALOG_COMPILER_APPICON_NAME": "AppIcon", "CODE_SIGNING_ALLOWED": "NO",
            "LD_RUNPATH_SEARCH_PATHS": ["$(inherited)", "@executable_path/Frameworks"],
        }))
    project_list = add("project.configs", "XCConfigurationList", buildConfigurations=project_configs, defaultConfigurationIsVisible="0", defaultConfigurationName="Release")
    target_list = add("target.configs", "XCConfigurationList", buildConfigurations=target_configs, defaultConfigurationIsVisible="0", defaultConfigurationName="Release")
    target = add("target", "PBXNativeTarget", buildConfigurationList=target_list, buildPhases=[sources, frameworks, resource_phase], buildRules=[], dependencies=[], name="Sonora", productName="Sonora", productReference=app, productType="com.apple.product-type.application")
    root = add("project", "PBXProject", attributes={"LastUpgradeCheck": "2600"}, buildConfigurationList=project_list, compatibilityVersion="Xcode 14.0", developmentRegion="en", hasScannedForEncodings="0", knownRegions=["en", "Base"], mainGroup=main_group, productRefGroup=products, projectDirPath="", projectRoot="", targets=[target])
    write_if_changed(IOS / "Sonora.xcodeproj/project.pbxproj", "// !$*UTF8*$!\n" + plist({"archiveVersion": "1", "classes": {}, "objectVersion": "56", "objects": objects, "rootObject": root}) + "\n")
    write_if_changed(IOS / "Sonora.xcodeproj/xcshareddata/xcschemes/Sonora.xcscheme", f'''<?xml version="1.0" encoding="UTF-8"?>
<Scheme LastUpgradeVersion="2600" version="1.3">
  <BuildAction parallelizeBuildables="YES" buildImplicitDependencies="YES"><BuildActionEntries>
    <BuildActionEntry buildForTesting="YES" buildForRunning="YES" buildForProfiling="YES" buildForArchiving="YES" buildForAnalyzing="YES">
      <BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="{target}" BuildableName="Sonora.app" BlueprintName="Sonora" ReferencedContainer="container:Sonora.xcodeproj"/>
    </BuildActionEntry>
  </BuildActionEntries></BuildAction>
  <LaunchAction buildConfiguration="Debug" selectedDebuggerIdentifier="Xcode.DebuggerFoundation.Debugger.LLDB" selectedLauncherIdentifier="Xcode.IDEFoundation.Launcher.LLDB" launchStyle="0" useCustomWorkingDirectory="NO" ignoresPersistentStateOnLaunch="NO" debugServiceExtension="internal" allowLocationSimulation="YES">
    <BuildableProductRunnable runnableDebuggingMode="0"><BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="{target}" BuildableName="Sonora.app" BlueprintName="Sonora" ReferencedContainer="container:Sonora.xcodeproj"/></BuildableProductRunnable>
  </LaunchAction>
  <ProfileAction buildConfiguration="Release"/>
  <AnalyzeAction buildConfiguration="Debug"/>
  <ArchiveAction buildConfiguration="Release" revealArchiveInOrganizer="YES"/>
</Scheme>
''')


if __name__ == "__main__":
    localization()
    icon()
    project()
    print("Prepared Sonora iPhone project, English strings and upstream icon.")
